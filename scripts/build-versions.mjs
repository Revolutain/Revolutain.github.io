// Renders the design versions listed in versions/_src/themes/*/theme.json
// from the shared pages and partials in versions/_src. Each output directory
// is a complete static site served from the root of its own hostname.
//
// Usage: node scripts/build-versions.mjs
//
// Template syntax (deliberately tiny, no dependencies):
//   {{> name}}                partial from versions/_src/partials/name.html
//   {{token}}                 value from the render context
//   {{#intro}} ... {{/intro}} kept only when the theme has an intro (not "none")
//   {{^intro}} ... {{/intro}} kept only when the theme has no intro

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = path.join(root, "versions", "_src");
const pagesDir = path.join(srcDir, "pages");
const partialsDir = path.join(srcDir, "partials");
const assetsDir = path.join(srcDir, "assets");
const themesDir = path.join(srcDir, "themes");
const manifestPath = path.join(root, "versions.json");

const PAGES = [
  { file: "index.html", out: "index.html", page: "home", label: "" },
  { file: "services.html", out: path.join("services", "index.html"), page: "services", label: "Services" },
  { file: "training.html", out: path.join("training", "index.html"), page: "training", label: "Training" },
  { file: "about.html", out: path.join("about", "index.html"), page: "about", label: "About" },
  { file: "contact.html", out: path.join("contact", "index.html"), page: "contact", label: "Contact" },
];

const DESCRIPTIONS = {
  home: "RevolutAIn helps owner-led businesses find where data and AI pay off, build what is worth building, and train the people who will use it. Partner-led, diagnostic-first, fixed-fee engagements.",
  services: "What RevolutAIn does, in the order it happens: an Operational Diagnostic, fixed-scope builds and training, and the retainers, fractional leadership, and governance work that keep it running.",
  training: "RevolutAIn training formats: a foundations workshop, a role accelerator, a six-week team enablement program, a leadership briefing, and a public cohort session. Live, instructor-led, built on your real tasks.",
  about: "RevolutAIn is three partners, one practice: a decision-science practitioner, a technology executive and educator, and an attorney and CPA. Partner-led work for owner-led businesses.",
  contact: "Book a 30-minute discovery call with RevolutAIn. We will ask about your business, listen for where the time and money go, and tell you honestly whether a diagnostic is worth it.",
};

const partialCache = new Map();
function partial(name) {
  if (!partialCache.has(name)) {
    const file = path.join(partialsDir, `${name}.html`);
    if (!fs.existsSync(file)) throw new Error(`missing partial: ${name}`);
    partialCache.set(name, fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n").replace(/\n$/, ""));
  }
  return partialCache.get(name);
}

function render(template, ctx, depth = 0) {
  if (depth > 20) throw new Error("partial recursion too deep");
  let out = template.replace(/\{\{>\s*([a-z0-9_-]+)\s*\}\}/gi, (_, name) => render(partial(name), ctx, depth + 1));
  out = out.replace(/\{\{#intro\}\}([\s\S]*?)\{\{\/intro\}\}/g, (_, body) => (ctx.hasIntro ? body : ""));
  out = out.replace(/\{\{\^intro\}\}([\s\S]*?)\{\{\/intro\}\}/g, (_, body) => (ctx.hasIntro ? "" : body));
  out = out.replace(/\{\{\s*([a-zA-Z0-9_]+)\s*\}\}/g, (match, key) => {
    if (!(key in ctx)) throw new Error(`unknown token {{${key}}}`);
    return String(ctx[key]);
  });
  return out;
}

function copyDir(from, to) {
  fs.mkdirSync(to, { recursive: true });
  fs.cpSync(from, to, { recursive: true });
}

const manifest = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, "utf8")) : { versions: [] };
const themes = fs
  .readdirSync(themesDir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => {
    const dir = path.join(themesDir, d.name);
    const theme = JSON.parse(fs.readFileSync(path.join(dir, "theme.json"), "utf8"));
    theme.dir = dir;
    for (const key of ["id", "slug", "title", "desc", "intro", "themeColor", "fonts"]) {
      if (!(key in theme)) throw new Error(`theme ${d.name} is missing "${key}"`);
    }
    if (!["takeover", "rings", "none"].includes(theme.intro)) throw new Error(`theme ${d.name}: intro must be takeover, rings, or none`);
    return theme;
  })
  .sort((a, b) => a.id.localeCompare(b.id));

const stamp = "<!-- Generated by scripts/build-versions.mjs from versions/_src. Edit the source, not this file. -->\n";

for (const theme of themes) {
  const outName = `${theme.id}-${theme.slug}`;
  const outDir = path.join(root, "versions", outName);
  const relDir = `versions/${outName}`;
  const entry = manifest.versions.find((v) => v.id === theme.id);
  if (!entry) console.warn(`warning: versions.json has no entry for id ${theme.id} (${outName})`);
  else if (entry.dir !== relDir) console.warn(`warning: versions.json entry ${theme.id} points at ${entry.dir}, generator writes ${relDir}`);

  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });

  for (const p of PAGES) {
    const template = fs.readFileSync(path.join(pagesDir, p.file), "utf8").replace(/\r\n/g, "\n");
    const ctx = {
      page: p.page,
      title: p.label ? `RevolutAIn | ${theme.title} | ${p.label}` : `RevolutAIn | ${theme.title}`,
      description: DESCRIPTIONS[p.page],
      fonts: theme.fonts,
      themeColor: theme.themeColor,
      intro: theme.intro,
      hasIntro: theme.intro !== "none",
      version: theme.title,
    };
    // Mark the current page in the header nav and the tab bar without JavaScript.
    const html = (stamp + render(template, ctx)).replace(new RegExp(`(<a [^>]*?)data-page="${p.page}"`, "g"), `$1data-page="${p.page}" aria-current="page"`);
    const target = path.join(outDir, p.out);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, html, "utf8");
  }

  const assetsOut = path.join(outDir, "assets");
  copyDir(assetsDir, assetsOut);
  fs.copyFileSync(path.join(theme.dir, "theme.css"), path.join(assetsOut, "theme.css"));
  console.log(`rendered ${relDir} (${theme.title}, intro: ${theme.intro})`);
}

console.log(`built ${themes.length} version(s) from versions/_src`);
